"""Shared HTTP helpers for the product evaluation workflow.

The WebUI sends ``X-API-Key`` / ``Authorization: Bearer`` on every eval request;
the CLI runners used to omit them, so any server with auth enabled rejected the
entire evaluation.  These helpers carry optional credentials through every
request so the CLI matches the WebUI client contract.
"""

from __future__ import annotations

import http.client
import json
import urllib.request
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit


def auth_headers(
    *,
    api_key: str | None = None,
    access_token: str | None = None,
) -> dict[str, str]:
    headers: dict[str, str] = {}
    if api_key:
        headers["X-API-Key"] = api_key
    if access_token:
        headers["Authorization"] = f"Bearer {access_token}"
    return headers


def post_json(
    url: str,
    payload: dict[str, Any],
    *,
    api_key: str | None = None,
    access_token: str | None = None,
    timeout: int = 180,
) -> dict[str, Any]:
    headers = {
        "Content-Type": "application/json",
        **auth_headers(api_key=api_key, access_token=access_token),
    }
    request = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers=headers,
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def get_json(
    url: str,
    *,
    api_key: str | None = None,
    access_token: str | None = None,
    timeout: int = 60,
) -> dict[str, Any]:
    request = urllib.request.Request(
        url,
        headers=auth_headers(api_key=api_key, access_token=access_token),
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def upload_file(
    path: Path,
    url: str,
    *,
    api_key: str | None = None,
    access_token: str | None = None,
    timeout: int = 600,
    process_options: str | None = None,
) -> dict[str, Any]:
    """Upload a document as multipart data without buffering it in memory."""
    parsed = urlsplit(url)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise ValueError(f"upload URL must be an absolute HTTP(S) URL: {url!r}")
    # Paths generated by the dataset service are ordinary filenames.  Still
    # prevent an unusual local filename from injecting another multipart header.
    filename = path.name.replace("\r", "").replace("\n", "").replace('"', "'")
    boundary = "----lightragMemoryEvalBoundary"
    extra_field = b""
    if process_options:
        extra_field = (
            f"--{boundary}\r\n"
            'Content-Disposition: form-data; name="process_options"\r\n'
            "\r\n"
            f"{process_options}\r\n"
        ).encode()
    prefix = (
        f"--{boundary}\r\n"
        f'Content-Disposition: form-data; name="file"; filename="{filename}"\r\n'
        "Content-Type: application/octet-stream\r\n\r\n"
    ).encode()
    suffix = f"\r\n--{boundary}--\r\n".encode()
    headers = {
        "Content-Type": f"multipart/form-data; boundary={boundary}",
        "Content-Length": str(
            len(prefix) + path.stat().st_size + len(suffix) + len(extra_field)
        ),
        **auth_headers(api_key=api_key, access_token=access_token),
    }
    target = parsed.path or "/"
    if parsed.query:
        target = f"{target}?{parsed.query}"
    connection_type = (
        http.client.HTTPSConnection
        if parsed.scheme == "https"
        else http.client.HTTPConnection
    )
    connection = connection_type(parsed.netloc, timeout=timeout)
    try:
        connection.putrequest("POST", target)
        for name, value in headers.items():
            connection.putheader(name, value)
        connection.endheaders()
        if extra_field:
            connection.send(extra_field)
        connection.send(prefix)
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                connection.send(chunk)
        connection.send(suffix)
        response = connection.getresponse()
        payload = response.read().decode("utf-8")
        if not 200 <= response.status < 300:
            raise RuntimeError(
                f"document upload failed with HTTP {response.status}: {payload[:1000]}"
            )
        return json.loads(payload)
    finally:
        connection.close()
